import { expect, test } from "./fixture";

test("待整理与正常时间线并存：按 ID 定位、手动修复、确认删除", async ({ page, app }) => {
	const photo = await app.photo();
	const text = "旧回忆的正文。".repeat(120);
	const common = { date: "2024-02-29", c: 3, text: "一起散步", photos: [] };
	await app.put("memories", "later", { ...common, title: "后来" });
	await app.put("memories", "earlier", { ...common, date: "2024-02-27", title: "此前" });
	await app.put("memories", "repair", { ...common, title: "   ", date: "2024-02-30", c: 2, text, photos: [photo], dlabel: "旧标签" });
	await expect(await page.request.put("/api/c/memories/remove", { data: { c: 1, photos: [], text: "待核实的记录" } })).toBeOK();
	await page.goto("/memories?item=repair");
	const pending = page.getByRole("region", { name: "待整理的回忆" });
	const repair = pending.getByRole("listitem").filter({ hasText: "2024-02-30" });
	await expect(page.locator("#memory-repair")).toBeFocused();
	await expect(page.locator("ol h2")).toHaveText(["后来", "此前"]);
	await expect(pending.locator("time")).toHaveCount(0);
	await expect(repair).toContainText("缺少标题");
	await repair.getByRole("button", { name: /编辑回忆/ }).click();
	const editor = page.getByRole("dialog", { name: "编辑回忆" });
	await expect(editor.getByLabel("日期")).toHaveValue("");
	await editor.getByLabel("标题").fill("重见天日");
	await editor.getByRole("button", { name: "保存回忆" }).click();
	await expect(editor).toBeVisible();
	await editor.getByLabel("日期").fill("2024-02-29");
	await editor.getByRole("button", { name: "保存回忆" }).click();
	await expect(editor).not.toBeVisible();
	await expect(page.locator("ol h2")).toHaveText(["后来", "重见天日", "此前"]);
	await expect(page.locator("#memory-repair")).toBeFocused();
	expect((await app.docs("memories")).find((m) => m.id === "repair")?.data).toEqual({ ...common, title: "重见天日", c: 2, text, photos: [photo], dlabel: "" });
	await page.reload();
	await expect(page.locator("#memory-repair")).toBeFocused();
	const remove = pending.getByRole("button", { name: /删除回忆/ });
	await remove.click();
	const confirm = page.getByRole("alertdialog");
	await expect(confirm).toContainText("未命名回忆");
	await confirm.getByRole("button", { name: "取消" }).click();
	await expect(pending).toContainText("待核实的记录");
	await remove.click();
	await confirm.getByRole("button", { name: "删除回忆" }).click();
	await expect(pending).toHaveCount(0);
	await expect.poll(async () => (await app.docs("memories")).map((m) => m.id)).not.toContain("remove");
});

test("Jia Qi 编辑只有历史共享地点的日记：恢复文字草稿不搬移地点，仍可单独填写和清空个人地点", async ({ page, app, site }) => {
	const side = { t: "", fav: "", photo: "" };
	const record = { date: "2024-03-01", kind: "apart" as const, title: "旧日记", place: "图书馆", yi: side, jq: { ...side, t: "旧正文" }, c: 1 };
	await app.put("diary", "history", record);
	await expect(await page.request.post("/api/login", { data: { password: site.partner } })).toBeOK();
	await page.goto("/diary");
	const card = page.getByRole("article").filter({ hasText: "旧日记" });
	const edit = card.getByRole("button", { name: "改我的这一边" });
	await expect(card.getByText("共享地点：图书馆")).toBeVisible();
	await edit.click();
	const editor = page.getByRole("dialog");
	await expect(editor.getByText("共享地点：图书馆")).toBeVisible();
	const place = editor.getByLabel("我在哪");
	await expect(place).toHaveValue("");
	await editor.getByLabel("正文", { exact: true }).fill("补上正文");
	await editor.getByRole("button", { name: "存草稿" }).click();
	await card.getByRole("button", { name: "继续写草稿" }).click();
	await expect(editor.getByLabel("正文", { exact: true })).toHaveValue("补上正文");
	await expect(place).toHaveValue("");
	const publish = editor.getByRole("button", { name: "发布", exact: true });
	await publish.click();
	await expect(editor).toHaveCount(0);
	expect((await app.docs("diary"))[0].data).toEqual({ ...record, jq: { ...side, t: "补上正文" } });
	await edit.click();
	await place.fill("图书馆");
	await publish.click();
	await expect(card.getByText("共享地点：图书馆")).toBeVisible();
	await expect(card.getByText("图书馆", { exact: true })).toBeVisible();
	await edit.click();
	await place.fill("");
	await publish.click();
	await expect(editor).toHaveCount(0);
	expect((await app.docs("diary"))[0].data).toEqual({ ...record, jq: { ...side, t: "补上正文", pl: "" } });
});
